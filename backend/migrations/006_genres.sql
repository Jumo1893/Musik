-- Genres bekommen eine Ordnung: grobe Hauptgenres wie Rock, Pop oder Hip-Hop und darunter
-- Untergenres wie Alternative Rock oder Punk Rock.
--
-- Grundlage ist die Wikipedia-Seite „List of music genres and styles“ (Revision 1385258216
-- vom 12.11.2026, https://en.wikipedia.org/wiki/List_of_music_genres_and_styles):
--   - Die Abschnitte der Liste sind die Hauptgenres, die Einträge darin ihre Untergenres –
--     auch tiefer verschachtelte (Britpop steht unter Alternative Rock, gehört also zu Rock).
--   - Die regionalen Abschnitte sind zu Latin, Reggae und Weltmusik zusammengefasst; „Bühne &
--     Film“ (Soundtrack, Musical …) und deutsche Bezeichnungen wie Deutschrap sind ergänzt.
--   - Ein Untergenre kann zu mehreren Hauptgenres gehören (Pop Rock: Pop und Rock).
--   - Einträge, die keine Genres sind („Music of Albania“, Instrumente), fehlen.
-- Die Namen stehen in Titelschreibweise; andere Schreibweisen (MusicBrainz, iTunes, Wikipedia-
-- Artikel) führt genre_aliases, damit sich z. B. „hip hop“ oder „Hip-Hop/Rap“ zuordnen lassen.
--
-- Songs speichern ihre Genres weiter als Namen in songs.genres. Genres, die die Liste nicht
-- kennt, legt die App als eigene Genres an (from_list = false).

CREATE TABLE genres (
    id        integer  GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name      text     NOT NULL CHECK (length(btrim(name)) > 0 AND length(name) <= 100),
    -- Hauptgenre wie „Rock“; sonst Untergenre wie „Alternative Rock“
    is_main   boolean  NOT NULL DEFAULT false,
    -- stammt aus der Genre-Liste; false: selbst eingetragen
    from_list boolean  NOT NULL DEFAULT false,
    -- Reihenfolge der Hauptgenres in Auswahllisten
    position  smallint
);

CREATE UNIQUE INDEX genres_unique_name ON genres (lower(name));

CREATE TABLE genre_parents (
    genre_id      integer NOT NULL REFERENCES genres (id) ON DELETE CASCADE,
    main_genre_id integer NOT NULL REFERENCES genres (id) ON DELETE CASCADE,
    PRIMARY KEY (genre_id, main_genre_id)
);

CREATE INDEX genre_parents_main_idx ON genre_parents (main_genre_id);

CREATE TABLE genre_aliases (
    alias    text    NOT NULL CHECK (length(btrim(alias)) > 0),
    genre_id integer NOT NULL REFERENCES genres (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX genre_aliases_unique ON genre_aliases (lower(alias));

-- Hauptgenres eines Songs: die genannten Hauptgenres und die der genannten Untergenres,
-- in der Reihenfolge der Auswahllisten.
CREATE FUNCTION song_main_genres(song_genres text[]) RETURNS text[]
LANGUAGE sql STABLE AS $$
    SELECT coalesce(array_agg(m.name ORDER BY m.position, m.name), '{}')
      FROM genres m
     WHERE m.is_main
       AND EXISTS (
           SELECT 1
             FROM unnest(song_genres) AS t(name)
             JOIN genres g ON lower(g.name) = lower(t.name)
            WHERE g.id = m.id
               OR EXISTS (SELECT 1 FROM genre_parents p WHERE p.genre_id = g.id AND p.main_genre_id = m.id))
$$;

