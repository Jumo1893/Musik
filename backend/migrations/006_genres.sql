INSERT INTO genre_aliases (alias, genre_id)
SELECT a.alias, g.id
  FROM genre_alias_list a
  JOIN genres g ON g.name = a.genre;

-- Vorhandene Genres der Songs auf die Schreibweise der Liste bringen: „Hip-Hop/Rap“ wird zu
-- „Hip-Hop“, „indie pop“ zu „Indie Pop“. Verglichen wird ohne Groß-/Kleinschreibung, Leer- und
-- Satzzeichen. Doppelte fallen weg, die Reihenfolge bleibt.
WITH known AS (
    SELECT g.name, regexp_replace(replace(lower(g.name), '&', 'and'), '[^[:alnum:]]+', '', 'g') AS key
      FROM genres g
    UNION ALL
    SELECT g.name, regexp_replace(replace(lower(a.alias), '&', 'and'), '[^[:alnum:]]+', '', 'g')
      FROM genre_aliases a
      JOIN genres g ON g.id = a.genre_id
)
UPDATE songs s
   SET genres = (
       SELECT coalesce(array_agg(x.name ORDER BY x.pos), '{}')
         FROM (SELECT DISTINCT ON (lower(n.name)) n.name, n.pos
                 FROM (SELECT coalesce((SELECT k.name FROM known k
                                         WHERE k.key = regexp_replace(replace(lower(t.genre), '&', 'and'), '[^[:alnum:]]+', '', 'g')
                                         LIMIT 1),
                                       btrim(t.genre)) AS name,
                              t.pos
                         FROM unnest(s.genres) WITH ORDINALITY AS t(genre, pos)) AS n
                ORDER BY lower(n.name), n.pos) AS x)
 WHERE s.genres <> '{}';

-- Was die Liste nicht kennt, bleibt erhalten und wird als eigenes Genre angelegt.
INSERT INTO genres (name)
SELECT DISTINCT ON (lower(t.genre)) t.genre
  FROM songs s
 CROSS JOIN LATERAL unnest(s.genres) AS t(genre)
 WHERE NOT EXISTS (SELECT 1 FROM genres g WHERE lower(g.name) = lower(t.genre))
 ORDER BY lower(t.genre), t.genre;

-- Ein eigenes Genre gehört zu den Hauptgenres, deren Name oder Schreibweise darin als Wort
-- vorkommt: „New wave pop“ gehört zu Pop.
INSERT INTO genre_parents (genre_id, main_genre_id)
SELECT DISTINCT c.id, m.id
  FROM genres c
  JOIN genres m ON m.is_main
  LEFT JOIN genre_aliases a ON a.genre_id = m.id
 WHERE NOT c.from_list
   AND ((' ' || btrim(regexp_replace(replace(lower(c.name), '&', ' and '), '[^[:alnum:]]+', ' ', 'g')) || ' ') LIKE '% ' || btrim(regexp_replace(replace(lower(m.name), '&', ' and '), '[^[:alnum:]]+', ' ', 'g')) || ' %'
        OR (' ' || btrim(regexp_replace(replace(lower(c.name), '&', ' and '), '[^[:alnum:]]+', ' ', 'g')) || ' ') LIKE '% ' || btrim(regexp_replace(replace(lower(a.alias), '&', ' and '), '[^[:alnum:]]+', ' ', 'g')) || ' %');
